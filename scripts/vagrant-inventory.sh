#!/usr/bin/env bash
#
# Translate `vagrant ssh-config` into the environment variables that
# inventories/vagrant/hosts.yml reads.
#
# vagrant-libvirt connects straight to the VM address on the provider-managed
# network, so the address is only known after `vagrant up`. Writing it to
# .vagrant/vagrant-env.sh keeps the checked-in inventory static.

set -euo pipefail

cd "$(dirname "$0")/.."

VM_NAME="${BASELINE_VM_NAME:-main}"
ENV_FILE=".vagrant/vagrant-env.sh"

if ! command -v vagrant >/dev/null 2>&1; then
  echo "vagrant is not installed" >&2
  exit 1
fi

ssh_config=$(vagrant ssh-config --host "$VM_NAME" 2>/dev/null) || {
  echo "Cannot read the SSH configuration for '$VM_NAME'." >&2
  echo "Is the VM running? Try: make vagrant-up" >&2
  exit 1
}

get() { printf '%s\n' "$ssh_config" | awk -v k="$1" '$1 == k {print $2; exit}'; }

host=$(get HostName)
port=$(get Port)
user=$(get User)
key=$(get IdentityFile)

if [ -z "$host" ] || [ -z "$key" ]; then
  echo "Could not parse 'vagrant ssh-config' output." >&2
  exit 1
fi

# IdentityFile may be relative to the project root.
case "$key" in
  /*) ;;
  *) key="$PWD/$key" ;;
esac

mkdir -p .vagrant
cat > "$ENV_FILE" <<EOF
# Generated by scripts/vagrant-inventory.sh. Do not edit.
export BASELINE_VAGRANT_HOST='$host'
export BASELINE_VAGRANT_PORT='${port:-22}'
export BASELINE_VAGRANT_USER='${user:-vagrant}'
export BASELINE_VAGRANT_KEY='$key'
EOF

echo "Wrote $ENV_FILE (host $host, port ${port:-22}, user ${user:-vagrant})"
